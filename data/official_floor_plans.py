def search_official_floor_plans(query):
    """
    Searches across all 4 floors and 7 blocks in OFFICIAL_FLOOR_PLANS.
    Returns matching room dicts with floor, block, roomNumber, roomName.
    """
    if not query or not query.strip():
        return []

    q = query.strip().lower()
    matches = []

    for floor_name, blocks in OFFICIAL_FLOOR_PLANS.items():
        for block_name, rooms in blocks.items():
            for r in rooms:
                rnum = r["roomNumber"].lower()
                rname = r["roomName"].lower()
                bname = block_name.lower()
                fname = floor_name.lower()

                if q in rnum or q in rname or q in bname or q in fname or rnum in q or rname in q:
                    matches.append({
                        "floor": floor_name,
                        "block": block_name,
                        "roomNumber": r["roomNumber"],
                        "roomName": r["roomName"],
                        "type": r.get("type", "General"),
                        "x": r.get("x", 450),
                        "y": r.get("y", 270),
                        "wings": r.get("wings", [])
                    })
    return matches
